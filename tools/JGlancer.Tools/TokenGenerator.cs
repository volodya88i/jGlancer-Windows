using System.Globalization;
using System.Text;
using System.Text.Json;

namespace JGlancer.Tools;

/// <summary>
/// docs/design-tokens.json (exported from the macOS JGDesign package) → JGTokens.g.cs: colors, metrics, spacing and the
/// type scale as C# constants, so XAML uses them through x:Static and code through the same names.
/// </summary>
internal static class TokenGenerator
{
    public static string Generate(string json)
    {
        using var document = JsonDocument.Parse(json);
        var root = document.RootElement;
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated>")
            .AppendLine("// Generated by tools/JGlancer.Tools (`tokens`) from docs/design-tokens.json. Do not edit by hand.")
            .AppendLine("// </auto-generated>")
            .AppendLine("namespace JGlancer.Design;")
            .AppendLine();

        AppendColors(code, root.GetProperty("colors"));
        AppendConstants(code, "JGMetrics", "Sizes in effective pixels (macOS points) from the macOS design system.",
            root.GetProperty("metrics"));
        AppendConstants(code, "JGSpacing", "The 4 px spacing grid.", root.GetProperty("spacing"));
        AppendTypeScale(code, root.GetProperty("typography"));
        return code.ToString();
    }

    private static void AppendColors(StringBuilder code, JsonElement colors)
    {
        code.AppendLine("/// <summary>Semantic color tokens (DESIGN.md §3). Never use raw colors in views.</summary>")
            .AppendLine("public static partial class JGColor")
            .AppendLine("{");
        var names = new List<string>();
        foreach (var color in colors.EnumerateArray())
        {
            var token = color.GetProperty("name").GetString()!;
            var name = Pascal(token);
            names.Add(name);
            var alpha = color.TryGetProperty("alpha", out var a) ? a.GetDouble() : 1.0;
            var args = new List<string>
            {
                Quote(token),
                $"dark: {Argb(color.GetProperty("dark").GetString()!, alpha)}",
                $"light: {Argb(color.GetProperty("light").GetString()!, alpha)}",
            };
            if (color.TryGetProperty("darkIncreasedContrast", out var darkIc))
            {
                args.Add($"darkIncreasedContrast: {Argb(darkIc.GetString()!, alpha)}");
            }
            if (color.TryGetProperty("lightIncreasedContrast", out var lightIc))
            {
                args.Add($"lightIncreasedContrast: {Argb(lightIc.GetString()!, alpha)}");
            }
            if (color.TryGetProperty("black", out var black))
            {
                args.Add($"black: {Argb(black.GetString()!, alpha)}");
            }
            code.AppendLine($"    /// <summary><c>{token}</c></summary>")
                .AppendLine($"    public static readonly JGColorToken {name} = new({string.Join(", ", args)});")
                .AppendLine();
        }
        code.AppendLine("    /// <summary>Every token, in the order of the design document.</summary>")
            .AppendLine($"    public static IReadOnlyList<JGColorToken> All {{ get; }} = [{string.Join(", ", names)}];")
            .AppendLine("}")
            .AppendLine();
    }

    private static void AppendConstants(StringBuilder code, string type, string summary, JsonElement values)
    {
        code.AppendLine($"/// <summary>{summary}</summary>")
            .AppendLine($"public static partial class {type}")
            .AppendLine("{");
        foreach (var property in values.EnumerateObject().OrderBy(p => p.Name, StringComparer.Ordinal))
        {
            code.AppendLine($"    public const double {Pascal(property.Name)} = {Number(property.Value.GetDouble())};");
        }
        code.AppendLine("}").AppendLine();
    }

    private static void AppendTypeScale(StringBuilder code, JsonElement styles)
    {
        code.AppendLine("/// <summary>The six text styles (DESIGN.md §4).</summary>")
            .AppendLine("public static partial class JGTypeScale")
            .AppendLine("{");
        var names = new List<string>();
        foreach (var style in styles.EnumerateArray())
        {
            var id = style.GetProperty("style").GetString()!;
            var name = Pascal(id);
            names.Add(name);
            var weight = style.GetProperty("weight").GetString() switch
            {
                "regular" => 400,
                "medium" => 500,
                "semibold" => 600,
                "bold" => 700,
                "heavy" => 800,
                var other => throw new InvalidDataException($"unknown weight {other}"),
            };
            var expanded = style.TryGetProperty("width", out var width) && width.GetString() == "expanded";
            var mono = style.TryGetProperty("design", out var design) && design.GetString()!.StartsWith("monospaced", StringComparison.Ordinal);
            var family = mono ? "Mono" : expanded ? "Display" : "Text";
            code.AppendLine(CultureInfo.InvariantCulture,
                $"    public static readonly JGTextStyle {name} = new({Quote(id)}, size: {Number(style.GetProperty("size").GetDouble())}, " +
                $"weight: {weight}, family: JGFontFamily.{family}, tracking: {Number(style.GetProperty("tracking").GetDouble())}, " +
                $"uppercase: {(style.GetProperty("uppercase").GetBoolean() ? "true" : "false")});");
        }
        code.AppendLine()
            .AppendLine($"    public static IReadOnlyList<JGTextStyle> All {{ get; }} = [{string.Join(", ", names)}];")
            .AppendLine("}");
    }

    /// <summary><c>bg.base</c> → <c>BgBase</c>, <c>tileSideDefault</c> → <c>TileSideDefault</c>.</summary>
    internal static string Pascal(string name)
    {
        var builder = new StringBuilder();
        var upper = true;
        foreach (var c in name)
        {
            if (c is '.' or '-' or '_')
            {
                upper = true;
                continue;
            }
            builder.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }
        return builder.ToString();
    }

    private static string Argb(string hex, double alpha)
    {
        var rgb = Convert.ToUInt32(hex.TrimStart('#'), 16);
        var a = (uint)Math.Round(alpha * 255);
        return $"0x{(a << 24) | rgb:X8}";
    }

    private static string Number(double value) => Math.Round(value, 4).ToString("0.####", CultureInfo.InvariantCulture);

    private static string Quote(string value) => $"\"{value}\"";
}
