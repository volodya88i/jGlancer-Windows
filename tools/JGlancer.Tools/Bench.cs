using System.Diagnostics;
using System.Globalization;
using System.Runtime.Versioning;
using JGlancer.Core.Model;
using JGlancer.Core.Scanning;
using JGlancer.Core.Store;
using JGlancer.Platform.Windows;

namespace JGlancer.Tools;

/// <summary>
/// Store and scanner benchmarks (the counterpart of the macOS <c>jgscan</c> harness). Read-only on the scanned folder;
/// the database lives in a fresh temporary file that is deleted afterwards.
/// </summary>
[SupportedOSPlatform("windows")]
internal static class Bench
{
    private const string Marker = ".jglancer-synthetic";

    /// <summary>
    /// Creates <paramref name="count"/> files in folders of 250 under %TEMP%\jGlancer-synthetic-N: tiny named files for
    /// stage-1 timing, or copies of the real fixtures with <paramref name="media"/> for stage 2. Refuses a non-empty
    /// folder it did not create.
    /// </summary>
    public static string Synthesize(int count, bool media, string fixtures)
    {
        var target = Path.Combine(Path.GetTempPath(), $"jGlancer-synthetic-{count}{(media ? "-media" : "")}");
        if (Directory.Exists(target) && Directory.EnumerateFileSystemEntries(target).Any() && !File.Exists(Path.Combine(target, Marker)))
        {
            throw new IOException($"{target} is not empty and was not created by this tool; refusing to write there");
        }
        Directory.CreateDirectory(target);
        File.WriteAllText(Path.Combine(target, Marker), "Generated by JGlancer.Tools synth; safe to delete.\n");
        string[] sources = ["photo_landscape.jpg", "photo.heic", "photo_alpha.png", "clip.mov", "tone_440_mono.wav", "tone_with_cover.m4a"];
        string[] extensions = ["jpg", "jpg", "jpg", "heic", "png", "mov", "mp4", "m4a", "mp3", "wav"];
        var clock = Stopwatch.StartNew();
        for (var i = 0; i < count; i++)
        {
            var folder = Path.Combine(target, $"{2000 + i / 25_000}", $"Album {i / 250:D4}");
            if (i % 250 == 0)
            {
                Directory.CreateDirectory(folder);
            }
            if (media)
            {
                var source = sources[i % sources.Length];
                File.Copy(Path.Combine(fixtures, source), Path.Combine(folder, $"IMG_{i:D6}{Path.GetExtension(source)}"), overwrite: true);
            }
            else
            {
                File.WriteAllText(Path.Combine(folder, $"IMG_{i:D6}.{extensions[i % extensions.Length]}"), i.ToString(CultureInfo.InvariantCulture));
            }
        }
        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"synthesized {count} files in {clock.Elapsed.TotalSeconds:0.0} s → {target}"));
        return target;
    }

    public static async Task<int> ScanAsync(string folder, bool metadata)
    {
        var database = Path.Combine(Path.GetTempPath(), $"jgscan-{Guid.NewGuid():N}.sqlite");
        try
        {
            using var store = LibraryStore.Open(database);
            var scanner = new LibraryScanner(store, new DirectoryLister(new WindowsDirectoryReader()), new WindowsMetadataReader());
            var process = Process.GetCurrentProcess();

            var clock = Stopwatch.StartNew();
            var (root, first) = await scanner.AddRootAsync(folder);
            Report("stage 1 (first scan)", clock.Elapsed, $"{first.Added} files in {first.Directories} folders, {first.UnreadableDirectories} unreadable");

            clock.Restart();
            var again = await scanner.ScanAsync(root.Id);
            Report("unchanged rescan", clock.Elapsed, $"{again.Unchanged} unchanged, changes: {again.HasChanges}");

            clock.Restart();
            var index = await store.AssetRefsAsync(new AssetQuery());
            Report("full sorted index", clock.Elapsed, $"{index.Count} refs");

            var folders = await store.FoldersAsync(root.Id);
            var oneFolder = folders.FirstOrDefault(f => f.RelativePath.Contains('/', StringComparison.Ordinal)) ?? folders[0];
            clock.Restart();
            var small = await store.AssetRefsAsync(new AssetQuery { Scope = QueryScope.InFolder(oneFolder.Id, false) });
            Report("one folder index", clock.Elapsed, $"{small.Count} refs");

            clock.Restart();
            var found = await store.AssetRefsAsync(new AssetQuery { Search = "0123" });
            Report("search \"0123\"", clock.Elapsed, $"{found.Count} hits");

            if (metadata)
            {
                clock.Restart();
                var processed = await scanner.ExtractMetadataAsync();
                var statistics = await store.StatisticsAsync();
                Report("stage 2 (metadata + hash)", clock.Elapsed,
                    string.Create(CultureInfo.InvariantCulture, $"{processed} files, {processed / Math.Max(clock.Elapsed.TotalSeconds, 0.001):0}/s, {statistics.PendingMetadata} pending"));
            }

            store.Read(connection => Sql.Execute(connection, "PRAGMA wal_checkpoint(TRUNCATE)"));
            var count = Math.Max(1, index.Count);
            var bytes = new FileInfo(database).Length;
            process.Refresh();
            Console.WriteLine(string.Create(CultureInfo.InvariantCulture,
                $"database: {bytes / 1024.0 / 1024.0:0.0} MB, {bytes / count} B per asset; peak working set {process.PeakWorkingSet64 / 1024 / 1024} MB"));
            return 0;
        }
        finally
        {
            Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
            foreach (var suffix in new[] { "", "-wal", "-shm" })
            {
                File.Delete(database + suffix);
            }
        }
    }

    private static void Report(string label, TimeSpan elapsed, string details) =>
        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"{label,-28} {elapsed.TotalMilliseconds,9:0} ms   {details}"));
}
