using System.Globalization;
using System.Text;
using System.Text.Json;

namespace JGlancer.Tools;

/// <summary>
/// Lucide icon nodes (lucide-static/icon-nodes.json, 24×24 stroke icons) → JGIconData.g.cs: one path-data string per
/// icon listed in icons.txt. Rects, circles, ellipses, lines and polylines become path commands so one geometry
/// strokes the whole icon.
/// </summary>
internal static partial class IconGenerator
{
    public static string Generate(string iconNodesJson, IEnumerable<string> names)
    {
        using var document = JsonDocument.Parse(iconNodesJson);
        var icons = document.RootElement;
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated>")
            .AppendLine("// Generated by tools/JGlancer.Tools (`icons`) from lucide-static icon-nodes.json (ISC licence,")
            .AppendLine("// see THIRD-PARTY-NOTICES.md) for the names in tools/JGlancer.Tools/icons.txt. Do not edit by hand.")
            .AppendLine("// </auto-generated>")
            .AppendLine("namespace JGlancer.Design;")
            .AppendLine()
            .AppendLine("/// <summary>Path data of the Lucide icons the app uses, on a 24 × 24 canvas, drawn as 2 px strokes.</summary>")
            .AppendLine("public static partial class JGIconData")
            .AppendLine("{");
        foreach (var line in names)
        {
            var name = line.Trim();
            if (name.Length == 0 || name.StartsWith('#'))
            {
                continue;
            }
            if (!icons.TryGetProperty(name, out var nodes))
            {
                throw new InvalidDataException($"lucide has no icon named {name}");
            }
            code.AppendLine($"    /// <summary>lucide <c>{name}</c></summary>")
                .AppendLine($"    public const string {TokenGenerator.Pascal(name)} = \"{PathData(nodes)}\";")
                .AppendLine();
        }
        code.AppendLine("}");
        return code.ToString();
    }

    internal static string PathData(JsonElement nodes)
    {
        var parts = new List<string>();
        foreach (var node in nodes.EnumerateArray())
        {
            var kind = node[0].GetString();
            var a = node[1];
            parts.Add(kind switch
            {
                "path" => Absolute(a.GetProperty("d").GetString()!),
                "line" => $"M{N(a, "x1")} {N(a, "y1")}L{N(a, "x2")} {N(a, "y2")}",
                "polyline" => Poly(a.GetProperty("points").GetString()!, close: false),
                "polygon" => Poly(a.GetProperty("points").GetString()!, close: true),
                "circle" => Ellipse(V(a, "cx"), V(a, "cy"), V(a, "r"), V(a, "r")),
                "ellipse" => Ellipse(V(a, "cx"), V(a, "cy"), V(a, "rx"), V(a, "ry")),
                "rect" => Rect(a),
                _ => throw new InvalidDataException($"unsupported node {kind}"),
            });
        }
        return string.Join(' ', parts);
    }

    /// <summary>
    /// A path's leading "m" is absolute in its own element (SVG) but would be relative to the previous subpath once
    /// the paths are joined into one, so its point becomes an absolute "M". The pairs after it are implicit relative
    /// lines and must stay relative, so they get an explicit "l" ("m9 18 6-6-6-6" → "M9 18l6-6-6-6").
    /// </summary>
    internal static string Absolute(string d)
    {
        var trimmed = d.TrimStart();
        if (!trimmed.StartsWith('m'))
        {
            return trimmed;
        }
        var match = MovePoint().Match(trimmed);
        if (!match.Success)
        {
            throw new InvalidDataException($"unreadable path start: {d}");
        }
        var point = $"M{match.Groups[1].Value} {match.Groups[2].Value}";
        var rest = trimmed[match.Length..].TrimStart(' ', ',');
        return rest.Length == 0 ? point : char.IsLetter(rest[0]) ? point + rest : point + "l" + rest;
    }

    // "m" then two numbers (SVG number syntax: sign, digits, optional fraction, separated by space, comma or a sign).
    [System.Text.RegularExpressions.GeneratedRegex(@"^m\s*(-?(?:\d+\.?\d*|\.\d+))[\s,]*(-?(?:\d+\.?\d*|\.\d+))")]
    private static partial System.Text.RegularExpressions.Regex MovePoint();

    private static string Rect(JsonElement a)
    {
        var x = V(a, "x");
        var y = V(a, "y");
        var w = V(a, "width");
        var h = V(a, "height");
        var rx = a.TryGetProperty("rx", out _) ? V(a, "rx") : 0;
        var ry = a.TryGetProperty("ry", out _) ? V(a, "ry") : rx;
        if (rx <= 0)
        {
            return $"M{F(x)} {F(y)}H{F(x + w)}V{F(y + h)}H{F(x)}Z";
        }
        return $"M{F(x + rx)} {F(y)}H{F(x + w - rx)}A{F(rx)} {F(ry)} 0 0 1 {F(x + w)} {F(y + ry)}" +
               $"V{F(y + h - ry)}A{F(rx)} {F(ry)} 0 0 1 {F(x + w - rx)} {F(y + h)}" +
               $"H{F(x + rx)}A{F(rx)} {F(ry)} 0 0 1 {F(x)} {F(y + h - ry)}" +
               $"V{F(y + ry)}A{F(rx)} {F(ry)} 0 0 1 {F(x + rx)} {F(y)}Z";
    }

    private static string Ellipse(double cx, double cy, double rx, double ry) =>
        $"M{F(cx - rx)} {F(cy)}A{F(rx)} {F(ry)} 0 1 0 {F(cx + rx)} {F(cy)}A{F(rx)} {F(ry)} 0 1 0 {F(cx - rx)} {F(cy)}Z";

    private static string Poly(string points, bool close)
    {
        var numbers = points.Split([' ', ','], StringSplitOptions.RemoveEmptyEntries);
        var builder = new StringBuilder();
        for (var i = 0; i + 1 < numbers.Length; i += 2)
        {
            builder.Append(i == 0 ? 'M' : 'L').Append(numbers[i]).Append(' ').Append(numbers[i + 1]);
        }
        if (close)
        {
            builder.Append('Z');
        }
        return builder.ToString();
    }

    private static double V(JsonElement a, string name)
    {
        var value = a.GetProperty(name);
        return value.ValueKind == JsonValueKind.Number
            ? value.GetDouble()
            : double.Parse(value.GetString()!, CultureInfo.InvariantCulture);
    }

    private static string N(JsonElement a, string name) => F(V(a, name));

    private static string F(double value) => value.ToString("0.###", CultureInfo.InvariantCulture);
}
